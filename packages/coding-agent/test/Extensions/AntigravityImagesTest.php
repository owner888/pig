<?php

declare(strict_types=1);

namespace Pig\CodingAgent\Test\Extensions;

use PHPUnit\Framework\TestCase;
use Pig\Ai\AssistantImages;
use Pig\Ai\Extension\ProviderRegistry;
use Pig\Ai\ImageApi;
use Pig\Ai\ImageContent;
use Pig\Ai\ImageModel;
use Pig\Ai\ImagesContext;
use Pig\Ai\ImagesOptions;
use Pig\Ai\Models;
use Pig\Ai\ModelType;
use Pig\Ai\StopReason;
use Pig\Ai\TextContent;
use Pig\Async\Async;
use Pig\Async\Loop;
use Pig\Test\CannedServer;
use PigAntigravity\ImageGenerator;

/**
 * Antigravity's image models as the core sees them: image models of the `antigravity` provider,
 * generated by `ImageGenerator` through `Models::generateImages()` — the path codemode's
 * `$models->generateImages()` and the `generate_image` tool both take.
 */
final class AntigravityImagesTest extends TestCase
{
    use LoadsAntigravity;

    private CannedServer $server;

    #[\Override]
    protected function setUp(): void
    {
        Loop::reset();
        self::loadAntigravity();
        $this->server = new CannedServer();
    }

    #[\Override]
    protected function tearDown(): void
    {
        ProviderRegistry::forget();
        Models::forgetRegistered();
    }

    private static function key(string $token = 'ya29.a', string $project = 'proj-1'): string
    {
        return (string) json_encode(['token' => $token, 'projectId' => $project]);
    }

    private static function model(string $id = ImageGenerator::DEFAULT_MODEL): ImageModel
    {
        $model = Models::findOfType(ModelType::Image, 'antigravity', $id);
        self::assertInstanceOf(ImageModel::class, $model);

        return $model;
    }

    private static function generate(string $prompt, ?string $key = null, array $metadata = [], array $references = []): AssistantImages
    {
        return Async::run(static fn (): AssistantImages => Models::generateImages(
            self::model(),
            new ImagesContext([new TextContent($prompt), ...$references]),
            new ImagesOptions(apiKey: $key ?? self::key(), metadata: $metadata),
        ));
    }

    /** @param list<array<string, mixed>> $chunks */
    private static function ok(array $chunks): array
    {
        $pieces = ["HTTP/1.1 200 OK\r\nContent-Type: text/event-stream\r\nTransfer-Encoding: chunked\r\n\r\n"];

        foreach ($chunks as $chunk) {
            $body = 'data: ' . json_encode($chunk) . "\n\n";
            $pieces[] = sprintf("%x\r\n%s\r\n", strlen($body), $body);
        }

        $pieces[] = "0\r\n\r\n";

        return $pieces;
    }

    private static function refusal(int $status, string $message): string
    {
        $body = (string) json_encode(['error' => ['message' => $message]]);

        return "HTTP/1.1 {$status} Refused\r\nContent-Length: " . strlen($body) . "\r\n\r\n" . $body;
    }

    /** @return array<string, mixed> */
    private static function imageChunk(string $data = 'aGVsbG8=', string $text = 'A cat.'): array
    {
        return ['response' => [
            'candidates' => [['content' => ['parts' => [['text' => $text], ['inlineData' => ['mimeType' => 'image/png', 'data' => $data]]]], 'finishReason' => 'STOP']],
            'usageMetadata' => ['promptTokenCount' => 12, 'candidatesTokenCount' => 1290, 'totalTokenCount' => 1302],
        ]];
    }

    public function testTheImageModelsAreTheProvidersWithWhatTheExtensionKnowsOfThem(): void
    {
        self::registerAntigravity();

        $ids = array_map(
            static fn (ImageModel $model): string => $model->id,
            array_values(array_filter(Models::allOfType(ModelType::Image), static fn (ImageModel $model): bool => $model->provider === 'antigravity')),
        );
        $this->assertSame(array_keys(ImageGenerator::MODELS), $ids);

        $model = self::model();
        $this->assertSame(ImageApi::Extension, $model->api);
        $this->assertSame('Gemini 3.1 Flash Image (Antigravity)', $model->name);
        $this->assertSame(['text', 'image'], $model->input);
        $this->assertSame(['image', 'text'], $model->output);
        $this->assertSame(0.0, $model->pricing->input, 'a subscription, as the chat models are');
    }

    public function testGeneratingThroughModelsSendsTheEnvelopeAndAnswersWithImagesAndUsage(): void
    {
        $url = $this->server->start(self::ok([self::imageChunk()]));
        self::registerAntigravity(images: new ImageGenerator(endpoint: $url));

        $result = self::generate('a cat', metadata: ['aspectRatio' => '16:9'], references: [new ImageContent('cmVm', 'image/jpeg')]);

        $this->assertSame(StopReason::Stop, $result->stopReason, (string) $result->errorMessage);
        $this->assertSame('antigravity', $result->provider);
        $this->assertSame(ImageGenerator::DEFAULT_MODEL, $result->model);
        $this->assertInstanceOf(TextContent::class, $result->output[0]);
        $this->assertSame('A cat.', $result->output[0]->text);
        $this->assertInstanceOf(ImageContent::class, $result->output[1]);
        $this->assertSame('aGVsbG8=', $result->output[1]->data);
        $this->assertSame(12, $result->usage?->input);
        $this->assertSame(1290, $result->usage?->output);
        $this->assertSame(1302, $result->usage?->totalTokens);
        $this->assertSame(0.0, $result->usage?->cost->total);

        $sent = $this->server->receivedJson();
        $this->assertSame('proj-1', $sent['project']);
        $this->assertSame(ImageGenerator::DEFAULT_MODEL, $sent['model']);
        $this->assertSame('16:9', $sent['request']['generationConfig']['imageConfig']['aspectRatio']);
        $this->assertSame([['text' => 'a cat'], ['inlineData' => ['mimeType' => 'image/jpeg', 'data' => 'cmVm']]], $sent['request']['contents'][0]['parts']);
        $this->assertStringContainsString('Bearer ya29.a', $this->server->received());
    }

    public function testA404MovesToTheNextModelAndTheResultSaysWhichOneAnswered(): void
    {
        $url = $this->server->startSequence([[self::refusal(404, 'no such model')], self::ok([self::imageChunk()])]);
        self::registerAntigravity(images: new ImageGenerator(endpoint: $url));

        $result = self::generate('a cat');

        $this->assertSame(StopReason::Stop, $result->stopReason, (string) $result->errorMessage);
        $this->assertSame('gemini-3-pro-image', $result->model, 'not silent: the model that answered');
    }

    public function testAQuotaWallFailsOverToTheNextAccount(): void
    {
        $tried = [];
        $failover = static function (array $tokens) use (&$tried): ?string {
            $tried[] = $tokens;

            return count($tried) === 1 ? self::key('second-token', 'second-project') : null;
        };
        $url = $this->server->startSequence([[self::refusal(429, 'Individual quota reached. Resets in 5m.')], self::ok([self::imageChunk()])]);
        self::registerAntigravity(images: new ImageGenerator(endpoint: $url, failover: $failover));

        $result = self::generate('a cat');

        $this->assertSame(StopReason::Stop, $result->stopReason, (string) $result->errorMessage);
        $this->assertSame([['ya29.a']], $tried);
        $this->assertSame(2, $this->server->connections());
        $this->assertStringContainsString('Bearer second-token', $this->server->received());
        $this->assertStringContainsString('"project":"second-project"', $this->server->received());
    }

    public function testEveryRefusalIsAnErrorResultInItsOwnWords(): void
    {
        self::registerAntigravity(images: new ImageGenerator(endpoint: 'http://127.0.0.1:9'));

        $ratio = self::generate('a cat', metadata: ['aspectRatio' => '3:5']);
        $this->assertSame(StopReason::Error, $ratio->stopReason);
        $this->assertStringStartsWith("Unsupported aspect ratio: '3:5'", (string) $ratio->errorMessage);

        $this->assertSame('Prompt cannot be empty.', self::generate('   ')->errorMessage);
        $this->assertStringContainsString('An ordinary Gemini API key cannot be used', (string) self::generate('a cat', 'AIza-plain')->errorMessage);
        $this->assertSame('Provider is not configured: antigravity', Models::generateImages(self::model(), new ImagesContext([new TextContent('x')]))->errorMessage);
    }

    public function testAnAnswerWithNoImageIsAFailureThatQuotesTheText(): void
    {
        $url = $this->server->start(self::ok([['response' => ['candidates' => [['content' => ['parts' => [['text' => 'I cannot draw that.']]]]]]]]));
        self::registerAntigravity(images: new ImageGenerator(endpoint: $url));

        $result = self::generate('a cat');

        $this->assertSame(StopReason::Error, $result->stopReason);
        $this->assertSame('Image generation failed: The response had no image in it: I cannot draw that.', $result->errorMessage);
        $this->assertSame(count(ImageGenerator::MODEL_FALLBACKS), $this->server->connections(), 'each model asked once');
    }

    public function testSaveWritesEveryImageAndNumbersThemWhenThereAreSeveral(): void
    {
        $dir = sys_get_temp_dir() . '/pig-ag-img-' . bin2hex(random_bytes(4));
        mkdir($dir);

        try {
            $result = new AssistantImages(ImageApi::Extension, 'antigravity', 'm', [new TextContent('t'), new ImageContent(base64_encode('one'), 'image/png'), new ImageContent(base64_encode('two'), 'image/jpeg')], StopReason::Stop, 0);
            $paths = ImageGenerator::save($result, 'out/', $dir);

            $this->assertCount(2, $paths);
            $this->assertStringEndsWith('-1.png', $paths[0]);
            $this->assertStringEndsWith('-2.jpg', $paths[1]);
            $this->assertSame('two', file_get_contents($paths[1]));
        } finally {
            foreach (glob($dir . '/out/*') ?: [] as $file) {
                unlink($file);
            }

            if (is_dir($dir . '/out')) {
                rmdir($dir . '/out');
            }
            rmdir($dir);
        }
    }
}
