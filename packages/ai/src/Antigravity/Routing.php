/**
 * Which model Antigravity is actually asked for, and by what name.
 *
 * **The ids people choose from are not the ids that go out.** `gemini-3.8-flash` is a *logical*
 * model; the thinking level picks a **runtime** id from it (`gemini-3.8-flash-medium`), and that
 * is sent as an **enum** (`MODEL_PLACEHOLDER_M319`). Three names for one choice, and a request
 * carrying the wrong one of the three is rejected rather than misrouted.
 *
 * Nothing in the rest of pig works this way: a `Model` has one id, and `ThinkingLevel` maps to a
 * reasoning effort rather than to another model. So this lives inside the provider — the registry
 * keeps offering one id per model, and the translation happens where the request is built. That
 * is also why it is here and not on `Model`: no other provider has an opinion about it.
 *
 * **The tables are generated, not transcribed.** `scripts/fetch-antigravity-models.php` prints
 * them from the deployment's own catalogue, which is the only authority there is — models.dev
 * does not carry a subscription deployment's catalogue and upstream deleted its Antigravity
 * support altogether. See the CLAUDE.md entry.
 *
 * Only the runtime ids reachable through routing are kept. The catalogue also enumerates the
 * Antigravity IDE's own models — tab completion, its chat surfaces, image generation, the
 * `-tiered` variants — and a table listing models nothing here can ask for is a table that
