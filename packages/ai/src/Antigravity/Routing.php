    /** Every logical model this provider can be asked for. */
    public static function models(): array
    {
        return array_keys(self::ROUTING);
    }

    public static function knows(string $model): bool
    {
        return isset(self::ROUTING[$model]);
    }

    /**
     * What to send for $model at $level: the runtime id and the enum it goes out as.
     *
     * $level is `ThinkingLevel`'s value, or null for a turn with thinking off.
     *
     * **An unknown model is an error, not a default.** The implementation this was ported from
     * ends its lookup chain with "otherwise Gemini 3.8 Flash", which is the right answer for a
     * gateway taking whatever a client sends and the wrong one here: pig's registry is built from
     * these very tables, so an id that misses can only be a bug in pig — and answering it with a
     * different model than the one on screen is the kind of bug that never gets found. Same for a
     * runtime id with no enum, which means the tables were regenerated inconsistently.
     *
     * @return array{string, string} the runtime id, and its enum
     */
    public static function resolve(string $model, ?string $level): array
    {
        $entry = self::ROUTING[$model]
            ?? throw new ProviderError("Antigravity has no model '{$model}'. Regenerate the routing tables with scripts/fetch-antigravity-models.php.");

        // `off` when there is one, the default when the model cannot be turned off. Reaching the
        // second is already unusual — `ThinkingLevel::supportedBy()` keeps `off` out of the
        // picker for those models — so this is the floor under that rather than a path in use.
        $runtime = $level === null || $level === 'off'
            ? ($entry['off'] ?? $entry['default'])
            : ($entry['levels'][$level] ?? $entry['default']);

        $enum = self::ENUMS[$runtime]
            ?? throw new ProviderError("Antigravity runtime model '{$runtime}' has no enum. The routing and enum tables disagree; regenerate both.");

        return [$runtime, $enum];
    }

    /**
     * How many tokens of thinking to ask for, by runtime id and level.
     *
     * **Hand-tuned and not from the catalogue**, which carries no budgets — ported as-is from a
     * working implementation, including the numbers that look arbitrary. `10001` and `1001` for
     * the Pro models are one more than the Flash figures and that is in the original too; a
     * rounder number here is a change to what the models are asked for, not a tidy-up.
     *
     * `-1` is Antigravity's "as much as you like" for Gemini at the top levels.
     */
    public static function thinkingBudget(string $runtime, ?string $level): int
    {
        if ($level === null || $level === 'off') {
            return 0;
        }

        if (str_starts_with($runtime, 'claude-')) {
            return 1024;
        }

        if (str_starts_with($runtime, 'gpt-oss-')) {
            return 8192;
        }

        if (str_starts_with($runtime, 'gemini-3.5-flash') || $runtime === 'gemini-3-flash-agent') {
            return match ($level) {
                'high', 'xhigh' => 10_000,
                'medium' => 4_000,
                default => 1_000,
            };
        }

        if (str_starts_with($runtime, 'gemini-3.1-pro') || $runtime === 'gemini-pro-agent') {
            return match ($level) {
                'high', 'xhigh' => 10_001,
                default => 1_001,
            };
        }

        if (str_starts_with($runtime, 'gemini-')) {
            return match ($level) {
                'high', 'xhigh' => -1,
                'medium' => 4_000,
                default => 1_000,
            };
        }

        return 0;
    }
