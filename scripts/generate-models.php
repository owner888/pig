    'xai' => [
        'grok-3',
        'grok-3-fast',
        'grok-4.20-0309-non-reasoning',
        'grok-4.20-0309-reasoning',
        'grok-build-0.1',
        'grok-code-fast-1',
    ],
];

/**
 * Which OpenAI API a Copilot model speaks.
 *
 * Upstream's rule, by id prefix, because Copilot serves both shapes and the catalogue does not
 * say which. `oswe` is VS Code's own preview model.
 */
function copilotApi(string $id): Api
{
    return str_starts_with($id, 'gpt-5') || str_starts_with($id, 'oswe')
        ? Api::OpenAiResponses
        : Api::OpenAiCompletions;
}

/** @return array<string, mixed> the models.dev document */
function catalogue(?string $file): array
{
    if ($file !== null) {
        if (!is_readable($file)) {
            fail("cannot read {$file}");
        }

        $text = (string) file_get_contents($file);
    } else {
        printf("fetching %s\n", MODELS_DEV);

        $text = Async::run(static function (): string {
            // `follow()` rather than `send()`: this is a file on somebody's CDN, not a streaming
            // API, so a 301 or 302 on the way to it is ordinary — which is the same reason
            // `ToolInstaller` uses it and the five providers do not.
            $response = (new HttpClient())->follow(new Request('GET', MODELS_DEV, ['accept' => 'application/json']));

            if (!$response->isSuccessful()) {
                fail(sprintf('models.dev answered %d', $response->status));
            }

            return $response->body->all();
        });
    }

    $data = json_decode($text, true);

    if (!is_array($data)) {
        fail('models.dev did not answer JSON: ' . json_last_error_msg());
    }

    return $data;
}

/**
 * One provider's rows, in the order the table keeps them.
 *
 * `tool_call !== true` is upstream's filter and it is not cosmetic: pig is an agent, so a model
 * that cannot be handed a tool cannot do the one thing it would be chosen for.
 *
 * @param array<string, mixed> $catalogue
 * @return array<string, array<string, mixed>>
 */
function rowsFor(array $catalogue, string $provider): array
{
    $models = $catalogue[$provider]['models'] ?? null;

    if (!is_array($models)) {
        // Named, not skipped: a provider that has vanished from models.dev is either a rename
        // this script has to learn or an endpoint that is gone, and both need a person.
        printf("  ! %s is not in this catalogue at all\n", $provider);

        return [];
    }

    $rows = [];

    foreach ($models as $id => $model) {
        if (!is_string($id) || !is_array($model)) {
            continue;
        }

        if (($model['tool_call'] ?? null) !== true) {
            continue;
        }

        // Copilot marks a retired model rather than removing it.
        if (($model['status'] ?? null) === 'deprecated') {
            continue;
        }

        if (in_array($id, EXCLUDED[$provider] ?? [], true)) {
            printf("  · %s/%s is listed and not offered — see EXCLUDED\n", $provider, $id);

            continue;
        }

        $input = $model['modalities']['input'] ?? [];

        $rows[$id] = [
            'name' => is_string($model['name'] ?? null) && $model['name'] !== '' ? $model['name'] : $id,
            'reasoning' => ($model['reasoning'] ?? null) === true,
            'images' => is_array($input) && in_array('image', $input, true),
            'context' => (int) ($model['limit']['context'] ?? 0),
            'output' => (int) ($model['limit']['output'] ?? 0),
            'input' => (float) ($model['cost']['input'] ?? 0),
            'out' => (float) ($model['cost']['output'] ?? 0),
            'cacheRead' => (float) ($model['cost']['cache_read'] ?? 0),
            'cacheWrite' => (float) ($model['cost']['cache_write'] ?? 0),
        ];
    }

    ksort($rows);

    return $rows;
}

/**
 * Upstream's defaults for a limit the catalogue left out.
 *
 * **Complained about rather than applied quietly.** Upstream writes `m.limit?.context || 4096`,
 * which turns a missing window into a number small enough to make every conversation look nearly
 * full, and a missing output cap into one that truncates every answer. The default is kept so a
 * row is still usable, and the complaint is what gets somebody to go and look.
 *
 * @param array<string, array<string, mixed>> $rows
 * @return array<string, array<string, mixed>>
 */
function fillLimits(array $rows, string $provider, int $window, int $output): array
{
    foreach ($rows as $id => $row) {
        if ($row['context'] <= 0) {
            printf("  ! %s/%s has no context window in the catalogue — using %d\n", $provider, $id, $window);
            $rows[$id]['context'] = $window;
        }

        if ($row['output'] <= 0) {
            printf("  ! %s/%s has no output limit in the catalogue — using %d\n", $provider, $id, $output);
            $rows[$id]['output'] = $output;
        }
    }

    return $rows;
}

/**
 * @param array<string, array<string, mixed>> $rows
 * @return array<string, array<string, mixed>>
 */
function applyOverrides(array $rows, string $provider): array
{
    foreach (OVERRIDES as $key => $override) {
        [$who, $id] = explode('/', $key, 2);

        if ($who !== $provider) {
            continue;
        }

        if ($override['kind'] === 'fix') {
            if (!isset($rows[$id])) {
                // The override outlived what it was correcting, which is worth saying rather
                // than carrying for ever.
                printf("  ! the override for %s has nothing to correct any more\n", $key);

                continue;
            }

            $fixed = [...$rows[$id], ...$override['row']];

            // **A correction that changes nothing is the interesting case**, and the first
            // version of this could not see it: a blind merge reports "corrected" whether or not
            // the catalogue still has it wrong, so the day models.dev fixes its own figure this
            // row becomes a no-op nobody retires. The `add` arm below already says when the
            // catalogue has caught up; this is the same sentence for the other kind.
            if ($fixed === $rows[$id]) {
                printf("  ! the override for %s changes nothing any more: %s\n", $key, $override['why']);

                continue;
            }

            $rows[$id] = $fixed;
            printf("  · %s corrected: %s\n", $key, $override['why']);

            continue;
        }

        if (isset($rows[$id])) {
            printf("  · the catalogue now carries %s, so the hand-written one is dropped\n", $key);

            continue;
        }

        $rows[$id] = $override['row'];
        printf("  · %s added by hand: %s\n", $key, $override['why']);
    }

    ksort($rows);

    return $rows;
}

/** A number the table writes with underscores, as every row in it already does. */
function grouped(int $value): string
{
    return number_format($value, 0, '.', '_');
}

/** A price, always with a decimal point so a column of them reads as money. */
function money(float $value): string
{
    $text = rtrim(rtrim(sprintf('%.10F', $value), '0'), '.');

    return $text === '' || !str_contains($text, '.') ? ($text === '' ? '0.0' : $text . '.0') : $text;
}

/**
 * The rows of one table, as the PHP text that goes between the markers.
 *
 * Three shapes, because the tables have three shapes and this writes what is there rather than
 * widening them: Anthropic has no images column (everything it sells takes images, and
 * `assertImages()` is what keeps that true), Copilot has an api column and no prices at all
 * (a subscription is not metered per token), and the other six are the full nine.
 *
 * @param array<string, array<string, mixed>> $rows
 */
function render(array $rows, string $constant): string
{
    $lines = [];

    foreach ($rows as $id => $row) {
        $cells = [var_export($row['name'], true)];

        if ($constant === 'COPILOT_MODELS') {
            $cells[] = 'Api::' . copilotApi($id)->name;
        }

        $cells[] = grouped((int) $row['context']);
        $cells[] = grouped((int) $row['output']);
        $cells[] = $row['reasoning'] ? 'true' : 'false';

        if ($constant !== 'ANTHROPIC_MODELS') {
            $cells[] = $row['images'] ? 'true' : 'false';
        }

        if ($constant !== 'COPILOT_MODELS') {
            foreach (['input', 'out', 'cacheRead', 'cacheWrite'] as $field) {
                $cells[] = money((float) $row[$field]);
            }
        }

        $lines[] = sprintf("        %s => [%s],", var_export($id, true), implode(', ', $cells));
    }

    return implode("\n", $lines);
}

/**
 * Anthropic's table cannot say "no images", so the assumption behind it is checked.
 *
 * @param array<string, array<string, mixed>> $rows
 */
function assertImages(array $rows): void
{
    foreach ($rows as $id => $row) {
        if ($row['images'] !== true) {
            printf("  ! anthropic/%s takes no images, which ANTHROPIC_MODELS has no column for\n", $id);
        }
    }
}

/** Replace what lies between one table's markers, and nothing else in the file. */
function splice(string $source, string $constant, string $rows): string
{
    $pattern = '/(private const array ' . preg_quote($constant, '/')
        . " = \\[\n        \\/\\/ >>> generated[^\n]*\n)(.*?)(\n        \\/\\/ <<< generated\n)/s";

    $replaced = preg_replace($pattern, '${1}' . str_replace('$', '\\$', $rows) . '${3}', $source, 1, $count);

    if ($replaced === null || $count !== 1) {
        fail("could not find the generated block for {$constant} — are its markers still there?");
    }

    return $replaced;
}

function fail(string $message): never
{
    fwrite(STDERR, "generate-models: {$message}\n");

    exit(1);
}

// ---- what changed --------------------------------------------------------------------------

/**
 * The table as it stands, before anything is written, keyed the way the file keys it.
 *
 * @return array<string, Model>
 */
function currently(): array
{
    $now = [];

    foreach (Models::all() as $model) {
        $now[$model->provider . '/' . $model->id] = $model;
    }

    return $now;
}

/**
 * @param array<string, Model> $before
 * @param array<string, Model> $after
 */
function report(array $before, array $after): void
{
    $gone = array_diff_key($before, $after);
    $added = array_diff_key($after, $before);
    $moved = [];

    foreach (array_intersect_key($after, $before) as $key => $model) {
        $was = $before[$key];
        $fields = [];

        if ($was->name !== $model->name) {
            $fields[] = sprintf('name %s → %s', $was->name, $model->name);
        }

        if ($was->contextWindow !== $model->contextWindow) {
            $fields[] = sprintf('window %d → %d', $was->contextWindow, $model->contextWindow);
        }

        if ($was->maxTokens !== $model->maxTokens) {
            $fields[] = sprintf('output %d → %d', $was->maxTokens, $model->maxTokens);
        }

        if ($was->reasoning !== $model->reasoning) {
            $fields[] = sprintf('reasoning %s → %s', $was->reasoning ? 'yes' : 'no', $model->reasoning ? 'yes' : 'no');
        }

        if ($was->acceptsImages() !== $model->acceptsImages()) {
            $fields[] = sprintf('images %s → %s', $was->acceptsImages() ? 'yes' : 'no', $model->acceptsImages() ? 'yes' : 'no');
        }

        foreach (['input', 'output', 'cacheRead', 'cacheWrite'] as $field) {
            if (abs($was->pricing->{$field} - $model->pricing->{$field}) > 1e-9) {
                $fields[] = sprintf('%s $%s → $%s', $field, money($was->pricing->{$field}), money($model->pricing->{$field}));
            }
        }

        if ($fields !== []) {
            $moved[$key] = $fields;
        }
    }

    printf("\n%d added, %d gone, %d changed\n", count($added), count($gone), count($moved));

    foreach (array_keys($added) as $key) {
        printf("  + %s\n", $key);
    }

    foreach (array_keys($gone) as $key) {
        printf("  - %s\n", $key);
    }

    foreach ($moved as $key => $fields) {
        printf("  ~ %s: %s\n", $key, implode('; ', $fields));
    }
}

