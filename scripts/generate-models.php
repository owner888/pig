declare(strict_types=1);

/**
 * Rewrite `Ai\Models`' tables from models.dev.
 *
 * `php scripts/generate-models.php [--from <file>] [--dry-run]`
 *
 * **Why this exists, which is the whole argument for it.** `Ai\Models` was a transcription: 178
 * rows copied by hand out of upstream's `models.generated.ts` at the anchor commit, and
 * `CLAUDE.md` called the freeze fidelity — *"the figures are upstream's at the anchor commit,
 * which is the source a port should agree with rather than whatever models.dev says today"*. That
 * is fidelity to the bytes and not to the mechanism. **Upstream has never kept this table by
 * hand**: the file pig copied from opens with
 *
 *     // This file is auto-generated by scripts/generate-models.ts
 *     // Do not edit manually - run 'npm run generate-models' to update
 *
 * and by upstream HEAD the data is not in git at all — each provider's catalogue is fetched from
 * models.dev at build time. So pig froze the *output* of a generator and then treated the freeze
 * as a decision. The price came due twice: Groq answered `404 … does not exist` for
 * `llama-3.3-70b-versatile`, a row `--list-models` still offered, and `gemini-3.8-flash` — a real
 * model — had to be hand-declared in `models.json` to be reachable at all.
 *
 * **Porting the anchor forward would not have fixed either**, because upstream HEAD has no table
 * to port. This is the thing that fixes it, and it leaves the port anchor exactly where it was:
 * `d0a4c37` still decides every line of *protocol*, and the registry stops being protocol and
 * goes back to being what it always was, a directory of what providers currently sell.
 *
 * What it does **not** do, on purpose:
 *
 * - **It writes rows, not files.** Each table in `Models.php` carries a `>>> generated` /
 *   `<<< generated` pair and only what lies between them is replaced, so every docblock, base
 *   URL, `RESOLD` entry and Copilot header stays hand-written and a regeneration's diff is the
 *   rows and nothing else.
 * - **It does not touch `ANTIGRAVITY_MODELS`.** That one is hand-written in
 *   *upstream's* generator too — models.dev does not carry a subscription deployment's catalogue —
 *   so they are hand-written here for the same reason and not for want of trying.
 * - **It does not add providers.** The filter is "the protocol is ported", which is `Models`' own
 *   standing rule: offering a model and then failing to send the request is a worse answer than
 *   "no such model". DeepSeek is the one worth naming — upstream ships it at HEAD, pig has no
 *   entry, and adding one is a decision about `OpenAiCompat` rather than a row in a table.
 * - **It never writes silently.** Every run prints what changed against the table that was
 *   loaded before the rewrite: added, gone, and every field that moved. A regeneration nobody
 *   read is a registry nobody checked.
 *
 * `--from` reads a saved `api.json` instead of fetching. Not a seam for a test: models.dev is
 * unreachable from some of the machines this repository is worked on, a regeneration from the
 * snapshot somebody else fetched is the only way to reproduce a table, and a generator whose
 * input cannot be pinned is a generator whose output cannot be explained.
 *
 * `--dry-run` writes nothing and prints the rows it would have written, which is the shape worth
 * reading before overwriting a table and is also the only way the rendering is checkable without
 * a file on disk to compare against.
 */

