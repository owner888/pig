printf("github-copilot\n");
$copilot = applyOverrides(fillLimits(rowsFor($catalogue, 'github-copilot'), 'github-copilot', 128_000, 8_192), 'github-copilot');

if ($copilot !== []) {
    $rendered = render($copilot, 'COPILOT_MODELS');
    $source = splice($source, 'COPILOT_MODELS', $rendered);
    $counts['github-copilot'] = count($copilot);

    if ($dryRun) {
        printf("%s\n", $rendered);
    }
} else {
    printf("  ! nothing to write for github-copilot, so its table is left as it is\n");
}

printf("\n");

foreach ($counts as $provider => $count) {
    printf("%-16s %d models\n", $provider, $count);
}

if ($dryRun) {
    printf("\n--dry-run: nothing written\n");

    exit(0);
}

if (file_put_contents(TABLE, $source) === false) {
    fail('could not write ' . TABLE);
}

// Re-read the table through a fresh process: this one has the old constants loaded, and PHP
// cannot be told to forget a class it has already resolved.
$reload = sprintf(
    '%s -r %s',
    escapeshellarg(PHP_BINARY),
    escapeshellarg(
        'require ' . var_export(__DIR__ . '/../vendor/autoload.php', true) . ';'
        . 'foreach (Pig\Ai\Models::all() as $m) { echo $m->provider, "/", $m->id, "\t", $m->name, "\t",'
        . '$m->contextWindow, "\t", $m->maxTokens, "\t", $m->reasoning ? 1 : 0, "\t",'
        . '$m->acceptsImages() ? 1 : 0, "\t", $m->pricing->input, "\t", $m->pricing->output, "\t",'
        . '$m->pricing->cacheRead, "\t", $m->pricing->cacheWrite, "\n"; }',
    ),
);

exec($reload, $output, $status);

if ($status !== 0) {
    fail('the rewritten table does not load — ' . TABLE . ' is written and needs looking at');
}

$after = [];

foreach ($output as $line) {
    [$key, $name, $window, $max, $reasoning, $images, $in, $out, $read, $write] = explode("\t", $line);
    [$provider, $id] = explode('/', $key, 2);
    $after[$key] = new Model(
        $id,
