/**
 * @param array<string, Model> $before
 * @param array<string, Model> $after
 */
function report(array $before, array $after): void
{
    $gone = array_diff_key($before, $after);
    $added = array_diff_key($after, $before);
    $moved = [];

    foreach (array_intersect_key($after, $before) as $key => $model) {
        $was = $before[$key];
        $fields = [];

        if ($was->name !== $model->name) {
            $fields[] = sprintf('name %s → %s', $was->name, $model->name);
        }

        if ($was->contextWindow !== $model->contextWindow) {
            $fields[] = sprintf('window %d → %d', $was->contextWindow, $model->contextWindow);
        }

        if ($was->maxTokens !== $model->maxTokens) {
            $fields[] = sprintf('output %d → %d', $was->maxTokens, $model->maxTokens);
        }

        if ($was->reasoning !== $model->reasoning) {
            $fields[] = sprintf('reasoning %s → %s', $was->reasoning ? 'yes' : 'no', $model->reasoning ? 'yes' : 'no');
        }

        if ($was->acceptsImages() !== $model->acceptsImages()) {
            $fields[] = sprintf('images %s → %s', $was->acceptsImages() ? 'yes' : 'no', $model->acceptsImages() ? 'yes' : 'no');
        }

        if ($was->thinkingLevelMap !== $model->thinkingLevelMap) {
            $fields[] = sprintf('levels %s → %s', json_encode($was->thinkingLevelMap), json_encode($model->thinkingLevelMap));
        }

        foreach (['input', 'output', 'cacheRead', 'cacheWrite'] as $field) {
            if (abs($was->pricing->{$field} - $model->pricing->{$field}) > 1e-9) {
                $fields[] = sprintf('%s $%s → $%s', $field, money($was->pricing->{$field}), money($model->pricing->{$field}));
            }
        }

        if (json_encode($was->pricing->tiers) !== json_encode($model->pricing->tiers)) {
            $fields[] = sprintf('tiers %s → %s', json_encode($was->pricing->tiers), json_encode($model->pricing->tiers));
        }

        if ($fields !== []) {
            $moved[$key] = $fields;
        }
    }

    printf("\n%d added, %d gone, %d changed\n", count($added), count($gone), count($moved));

    foreach (array_keys($added) as $key) {
        printf("  + %s\n", $key);
    }

    foreach (array_keys($gone) as $key) {
        printf("  - %s\n", $key);
    }

    foreach ($moved as $key => $fields) {
        printf("  ~ %s: %s\n", $key, implode('; ', $fields));
    }
}

