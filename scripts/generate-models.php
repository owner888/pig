/**
 * Models the catalogue carries and pig does not offer.
 *
 * Upstream HEAD's `XAI_BUILTIN_EXCLUDED_MODEL_IDS`, applied as a straight filter the way upstream
 * applies it. It is knowledge models.dev does not carry — that these ids are listed and are not
 * usable — and it is the same kind of knowledge as the overrides above, one direction over.
 *
 * **Ported because the first real regeneration needed it.** `xai/grok-code-fast-1` had an
 * anchor-era `add` override here, on the grounds that models.dev did not list it. The override had
 * never fired, because at the anchor the catalogue *did* carry the model — with a 256,000 window,
 * a 10,000 output cap and reasoning on, which is what pig's transcribed row held. models.dev has
 * since dropped it, so the override fired for the first time and **replaced a good row with the
 * stale fallback beside it**: window 256000 → 32768, output 10000 → 8192, reasoning yes → no. An
 * override that has never been exercised is an override nobody has checked.
 *
 * Asking upstream what it thinks now settled which way to fix it: HEAD excludes that id outright,
 * along with `grok-3`, `grok-3-fast` and two preview ids. So the catalogue dropping it and
 * upstream excluding it agree, and re-adding it under any numbers would be offering a model that
 * cannot be talked to — which is the rule at the top of `Models` and the Groq 404 all over again.
 *
 * The reason upstream excludes each is not in its source and is not guessed at here. What is
 * checkable is that its list and models.dev disagree, and that following upstream is the safer
 * side of that disagreement.
 *
 * @var array<string, list<string>>
 */
